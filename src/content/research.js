function overlaps(range, band) {
  return Array.isArray(range) && range[0] <= band[1] && range[1] >= band[0];
}

function coverageForBand(dimensionId, band) {
  const works = RESEARCH_WORKS.filter((work) => work.claims.some((item) => item.dimensionId === dimensionId && overlaps(item.positionRange, band))).map(({ id }) => id);
  const people = RESEARCH_PEOPLE.filter((person) => overlaps(person.profile?.[dimensionId]?.range, band)).map(({ id }) => id);
  const total = new Set([...works, ...people]).size;
  return { works, people, total, status: total >= 3 ? 'strong' : total >= 1 ? 'thin' : 'gap' };
}

